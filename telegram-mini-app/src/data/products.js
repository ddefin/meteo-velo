// Catalogue complet olfazeta — généré à partir du tarif fournisseur (parfums "inspirés de",
// créations originales Signature, collection Maison, accessoires). Remplacez `image` par de
// vraies photos produit quand elles sont disponibles ; le fallback visuel gère l'absence d'image.

function inspired(id, name, brand, category, size, price, tier) {
  const description =
    tier === "Luxury"
      ? "Format découverte de notre collection Luxury : les créations les plus exclusives, inspirées des maisons de niche les plus prisées."
      : tier === "Luxe"
      ? "Collection Luxe : qualité extrait de parfum concentré à 30 %, une interprétation haut de gamme des plus grandes signatures olfactives."
      : "Extrait de parfum concentré à 30 %, la qualité la plus haute en parfumerie, pour une tenue longue durée.";
  return {
    id,
    name,
    category,
    tier,
    subtitle: `Inspiré de ${brand} · ${tier || "Extrait de Parfum 30%"} · ${size}`,
    price,
    image: "",
    description,
  };
}

